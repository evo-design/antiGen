#!/usr/bin/env python
"""Write tutorial/tutorial.ipynb and TUTORIAL.md from tutorial/tutorial.py, so the three
never drift.

    python tutorial/build.py [--outputs executed.ipynb]

Cells are split on `# %%` lines; `# %% [markdown]` cells become markdown (their leading
`# ` stripped). The commented `# %pip install` line becomes a live cell in the notebook.
TUTORIAL.md shows each code cell followed by its output, taken from an EXECUTED copy of
the notebook (--outputs; run it first, e.g. with nbclient), so the outputs shown are
ones the code produced.
"""
import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
src = open(os.path.join(HERE, "tutorial.py")).read().splitlines()

cells, cur, kind = [], [], None
def flush():
    if kind is None:
        return
    lines = list(cur)
    while lines and not lines[-1].strip():
        lines.pop()
    if kind == "markdown":
        lines = [l[2:] if l.startswith("# ") else l.lstrip("#") for l in lines]
    else:
        lines = [l[2:] if l.startswith("# %pip") else l for l in lines]
    text = [l + "\n" for l in lines]
    if text:
        text[-1] = text[-1].rstrip("\n")
    cell = {"cell_type": kind, "metadata": {}, "source": text}
    if kind == "code":
        cell.update(execution_count=None, outputs=[])
    cells.append(cell)

for line in src:
    if line.startswith("# %%"):
        flush()
        kind, cur = ("markdown" if "[markdown]" in line else "code"), []
    else:
        cur.append(line)
flush()

nb = {"nbformat": 4, "nbformat_minor": 5, "cells": cells,
      "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                  "name": "python3"},
                   "language_info": {"name": "python"}}}
for i, c in enumerate(nb["cells"]):
    c["id"] = f"cell-{i:02d}"
with open(os.path.join(HERE, "tutorial.ipynb"), "w") as f:
    json.dump(nb, f, indent=1, ensure_ascii=False)
    f.write("\n")
print(f"wrote tutorial.ipynb: {len(cells)} cells")

ap = argparse.ArgumentParser()
ap.add_argument("--outputs", help="an executed copy of tutorial.ipynb")
a = ap.parse_args()
outs = {}
if a.outputs:
    ex = json.load(open(a.outputs))
    assert len(ex["cells"]) == len(cells), "executed notebook is not this tutorial; re-run it"
    for i, (c, e) in enumerate(zip(cells, ex["cells"])):
        if c["cell_type"] == "code":       # prose edits need no re-run; code edits do
            assert "".join(c["source"]) == "".join(e["source"]), f"cell {i} changed; re-run it"
        text = ""
        for o in e.get("outputs", []):
            if o["output_type"] == "error":
                raise SystemExit(f"cell {i} raised {o['ename']}: re-run it")
            t = o.get("text") or o.get("data", {}).get("text/plain", "")
            text += "".join(t) if isinstance(t, list) else t
        outs[i] = text.strip()

md = ["<!-- Generated by tutorial/build.py from tutorial/tutorial.py; edit that file. -->", ""]
for i, c in enumerate(cells):
    body = "".join(c["source"])
    if c["cell_type"] == "markdown":
        md += [body, ""]
    elif body.startswith("%pip"):
        md += ["```bash", body.replace("%pip", "pip", 1), "```", ""]
    else:
        md += ["```python", body, "```", ""]
        if outs.get(i):
            md += ["```text", outs[i], "```", ""]
open(os.path.join(ROOT, "TUTORIAL.md"), "w").write("\n".join(md).rstrip() + "\n")
print("wrote TUTORIAL.md" + (" (with outputs)" if outs else " (no outputs: pass --outputs)"))
